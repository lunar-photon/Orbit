#!/usr/bin/env python3
"""Write wcwidth_table.h: the cell width of every code point that isn't 1, as ranges, taken
from the same `wcwidth` package pyte uses, so the C++ screen lines up text the same way.

    python3 gen_wcwidth.py > wcwidth_table.h
"""
import wcwidth

ranges = []
for cp in range(0x110000):
    if 0xD800 <= cp <= 0xDFFF:
        w = -1
    else:
        w = wcwidth.wcwidth(chr(cp))
    if w == 1:
        continue
    if ranges and ranges[-1][1] == cp - 1 and ranges[-1][2] == w:
        ranges[-1][1] = cp
    else:
        ranges.append([cp, cp, w])
print(f'// Generated by gen_wcwidth.py from wcwidth {wcwidth.__version__}; do not edit.')
print('// {first, last, width} for every code point whose width is not 1, sorted.')
print('static const struct { unsigned first, last; int width; } WIDTHS[] = {')
for i in range(0, len(ranges), 4):
    print('    ' + ' '.join(f'{{0x{a:x}, 0x{b:x}, {w}}},' for a, b, w in ranges[i:i + 4]))
print('};')
